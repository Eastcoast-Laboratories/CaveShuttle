    let rejectWarnings = false;

    for (let i = 0; i < args.length; i++) {
      if (args[i] === '--output' || args[i] === '-o') {
        outputFile = args[++i];
      } else if (args[i] === '--seed' || args[i] === '-s') {
        seed = parseInt(args[++i], 10);
      } else if (args[i] === '--width' || args[i] === '-w') {
        width = parseInt(args[++i], 10);
      } else if (args[i] === '--height' || args[i] === '-h') {
        height = parseInt(args[++i], 10);
      } else if (args[i] === '--bunkers' || args[i] === '-b') {
        bunkers = parseInt(args[++i], 10);
      } else if (args[i] === '--fuel') {
        fuel = parseInt(args[++i], 10);
      } else if (args[i] === '--bunker-chance') {
        bunkerChance = parseFloat(args[++i]);
      } else if (args[i] === '--fuel-chance') {
        fuelChance = parseFloat(args[++i]);
      } else if (args[i] === '--require-door') {
        requireDoor = true;
      } else if (args[i] === '--reject-warnings') {
        rejectWarnings = true;
      }
    }

    generateValidRandomLevel({ width, height, seed, bunkers, fuel, bunkerChance, fuelChance, requireDoor, rejectWarnings }).then(levelText => {
      if (outputFile) {
        import('node:fs').then(({ writeFileSync }) => {
          writeFileSync(outputFile, levelText + '\n');
          console.log(`[OK] Generated valid level written to ${outputFile}`);
        });
      } else {
        console.log(levelText);
      }
    }).catch(err => {
      console.error(err.message);
      process.exit(1);
    });
