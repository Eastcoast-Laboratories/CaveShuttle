// Random level generator for CaveShuttle .def levels.
// Usable from CLI:  node public/level-editor/level-generator.js [--output file.def] [--seed N]
// Usable from browser: window.generateRandomLevel(opts) -> string
//
// How it works:
//   1. Creates a grid filled with wall tiles ('p') of width x height.
//   2. Carves a winding path from top (sky) to bottom (pod chamber) by
//      alternating full-width horizontal corridors and narrower vertical shafts.
//   3. Places the pod holder at the bottom and ensures an open cell above it.
//   4. Optionally adds slopes (qr/st/uv/wx) to ~90% of corridors, then
//      re-opens corridor boundary rows to maintain vertical connectivity.
//   5. Places features along corridors: fuel depots (with wall below and
//      2-row clearance above), bunkers (on left/right walls), reactors,
//      doors with buttons, and checkpoints.
//   6. Runs a slope-continuity post-processing pass: ensures qr/st have wall
//      below and uv/wx have wall above, then re-opens corridor boundaries again.
//   7. Serializes the grid to .def text with a 10-line header.
//   generateValidRandomLevel() wraps this in a retry loop (up to 100 attempts)
//   that re-generates with incrementing seeds until the validator passes.

'use strict';

  const DEFAULT_WIDTH = 182;
  const DEFAULT_HEIGHT = 120;
  const RIGHT_SURFACE_HILL_WIDTH = 100;
  const MOVE_COLUMNS_TARGET = 20;
  const SKY_ROWS = 15;
  const FLOOR_ROWS = 0; // bedrock is generated by the game from the .def header
  const START_HEIGHT = 0;
  const EMPTY_SPACE_HEIGHT = -5;
  const BEDROCK_HEIGHT = 25;
  const MIN_SHAFT_WIDTH = 8;
  const MIN_CORRIDOR_HEIGHT = 10;
  const CORRIDOR_RANDOM_EXTRA_HEIGHT = 6;

  const MIN_RESPAWN_OBSTACLE_DISTANCE_BELOW = 4;
  const MIN_RESPAWN_HORIZONTAL_CLEARANCE = 4;

  // Random solid-wall margin inserted between a decorative slope and the level
  // edge so slopes don't all cling to the outer wall. Kept small so the
  // vertical shafts feeding the corridor above/below are not walled off.
  const SLOPE_EDGE_MARGIN_MIN = 0;
  const SLOPE_EDGE_MARGIN_MAX = 4;
  // Minimum vertical gap (rows) kept between a ceiling slope and a floor slope
  // on the same side of a corridor so they never stack on top of each other.
  const SLOPE_VERTICAL_GAP = 2;

  // Obstacle tiles for respawn-point clearance: anything that is not an open
  // cell, and the H/G endpoints of a sliding door.
  function isObstacleTile(grid, r, c) {
    if (r < 0 || r >= grid.length || c < 0 || c >= grid[0].length) return true;
    const ch = grid[r][c];
    if (ch === ' ' || ch === 'm' || ch === '0' || ch === '1' || ch === '2' || ch === '#') return false;
    return ch.charCodeAt(0) >= 76 || ch === 'H' || ch === 'G';
  }

  // ---- RNG ----
  function mulberry32(seed) {
    return function () {
      seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
      let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  // ---- Grid helpers ----
  function makeGrid(w, h, fill) {
    const g = [];
    for (let r = 0; r < h; r++) g.push(new Array(w).fill(fill));
    return g;
  }

  function setChar(grid, r, c, ch) {
    if (r >= 0 && r < grid.length && c >= 0 && c < grid[0].length) grid[r][c] = ch;
  }

  function setRange(grid, r, c0, c1, ch) {
    for (let c = Math.max(0, c0); c < Math.min(grid[0].length, c1); c++) grid[r][c] = ch;
  }

  function vrange(grid, r0, r1, c0, c1, ch) {
    for (let r = Math.max(0, r0); r < Math.min(grid.length, r1); r++)
      for (let c = Math.max(0, c0); c < Math.min(grid[0].length, c1); c++)
        grid[r][c] = ch;
  }

  function corridor(grid, r, leftEnd, rightStart) {
    setRange(grid, r, leftEnd, rightStart, ' ');
  }

  function vcorridor(grid, r0, r1, c0, c1) {
    vrange(grid, r0, r1, c0, c1, ' ');
  }

  function isWallTile(grid, r, c) {
    if (r < 0 || r >= grid.length || c < 0 || c >= grid[0].length) return true;
    const ch = grid[r][c];
    if (ch === ' ' || ch === 'm' || ch === '0' || ch === '1' || ch === '2') return false;
    // Visible pod stand tiles (3, 4) are not kolliding either
    if (ch === '3' || ch === '4') return false;
    return ch.charCodeAt(0) >= 76;
  }

  // ---- Feature placers ----
  function placeFuel(grid, r, c) {
    setChar(grid, r, c, '`');
    setChar(grid, r, c + 1, 'a');
    setChar(grid, r + 1, c, 'b');
    setChar(grid, r + 1, c + 1, 'c');
  }

  function placeReactor(grid, r, c) {
    const pat = ['def', 'ghi', 'jkl'];
    for (let dy = 0; dy < 3; dy++)
      for (let dx = 0; dx < 3; dx++)
        setChar(grid, r + dy, c + dx, pat[dy][dx]);
  }

  function placePod(grid, r, c) {
    setChar(grid, r, c, 'm');
    setChar(grid, r, c + 1, '0');
    setChar(grid, r + 1, c, '1');
    setChar(grid, r + 1, c + 1, '2');
    setChar(grid, r + 2, c, '3');
    setChar(grid, r + 2, c + 1, '4');
  }

  function placeDoorRow(grid, r, hc, gc) {
    // Three-row-thick horizontal slider with H/G endpoints and p wall between.
    for (const dr of [-1, 0, 1]) {
      setChar(grid, r + dr, hc, 'H');
      setChar(grid, r + dr, gc, 'G');
      for (let c = hc + 1; c < gc; c++) setChar(grid, r + dr, c, 'p');
    }
  }

  // Ceiling bunker: [ facing right, wall descends from upper-right (uv slope)
  // leftCol = left corridor boundary. Bunker row is r1, slope starts above at r0.
  // Template: uv shifts left 2 cols per row going down.
  // r1 row:    ppppuv[
  // r1+1 row:  ppuvXYZ
  // r1+2 row:  uv
  function placeBunkerBracket(grid, r0, r1, leftCol) {
    const rightCol = grid[0].length;
    for (let r = r0; r <= r1 + 2; r++) {
      const rowsBelow = r1 - r;
      const c = leftCol + 3 + rowsBelow * 2;
      if (c < 0 || c + 1 >= rightCol) continue;
      for (let c2 = leftCol; c2 < c; c2++) setChar(grid, r, c2, 'p');
      if (r === r0) {
        // The top row is the ceiling boundary: uv slope starts here.
        setChar(grid, r, c, 'u'); setChar(grid, r, c + 1, 'v');
      } else {
        setChar(grid, r, c, 'u'); setChar(grid, r, c + 1, 'v');
      }
      if (r === r1) setChar(grid, r, c + 2, '[');
      if (r === r1 + 1) {
        setChar(grid, r, c + 2, 'X');
        setChar(grid, r, c + 3, 'Y');
        setChar(grid, r, c + 4, 'Z');
      }
    }
  }

  // Offset variant of placeBunkerBracket that starts p-fill at startCol instead of col 0.
  // This allows multiple ceiling bunkers in the same corridor at different horizontal positions.
  function placeBunkerBracketAt(grid, r0, r1, startCol) {
    for (let r = r0; r <= r1 + 2; r++) {
      const rowsBelow = r1 - r;
      const c = startCol + 3 + rowsBelow * 2;
      if (c < 0 || c + 1 >= grid[0].length) continue;
      for (let c2 = startCol; c2 < c; c2++) setChar(grid, r, c2, 'p');
      setChar(grid, r, c, 'u'); setChar(grid, r, c + 1, 'v');
      if (r === r1) setChar(grid, r, c + 2, '[');
      if (r === r1 + 1) {
        setChar(grid, r, c + 2, 'X');
        setChar(grid, r, c + 3, 'Y');
        setChar(grid, r, c + 4, 'Z');
      }
    }
  }

  // Ceiling bunker: \ facing left, wall descends from upper-left (wx slope)
  // rightCol = exclusive right corridor boundary. Bunker row is r1, slope starts above at r0.
  // Template: wx shifts right 2 cols per row going down.
  // r1 row:    \wxpp
  // r1+1 row:  ]^_wxpp
  // r1+2 row:  wx
  function placeBunkerBackslash(grid, r0, r1, rightCol) {
    const maxCol = grid[0].length;
    for (let r = r0; r <= r1 + 2; r++) {
      const rowsBelow = r1 - r;
      const c = rightCol - 6 - rowsBelow * 2;
      if (c < 0 || c + 1 >= maxCol) continue;
      if (c + 2 < maxCol) {
        for (let c2 = c + 2; c2 < maxCol; c2++) setChar(grid, r, c2, 'p');
      }
      if (r === r0) {
        setChar(grid, r, c, 'w'); setChar(grid, r, c + 1, 'x');
      } else {
        setChar(grid, r, c, 'w'); setChar(grid, r, c + 1, 'x');
      }
      if (r === r1 && c - 1 >= 0) setChar(grid, r, c - 1, '\\');
      if (r === r1 + 1 && c - 3 >= 0) {
        setChar(grid, r, c - 3, ']');
        setChar(grid, r, c - 2, '^');
        setChar(grid, r, c - 1, '_');
      }
    }
  }

  // Offset variant of placeBunkerBackslash that ends p-fill at endCol instead of grid width.
  function placeBunkerBackslashAt(grid, r0, r1, rightCol) {
    for (let r = r0; r <= r1 + 2; r++) {
      const rowsBelow = r1 - r;
      const c = rightCol - 6 - rowsBelow * 2;
      if (c < 0 || c + 1 >= grid[0].length) continue;
      if (c + 2 < rightCol) {
        for (let c2 = c + 2; c2 < rightCol; c2++) setChar(grid, r, c2, 'p');
      }
      setChar(grid, r, c, 'w'); setChar(grid, r, c + 1, 'x');
      if (r === r1 && c - 1 >= 0) setChar(grid, r, c - 1, '\\');
      if (r === r1 + 1 && c - 3 >= 0) {
        setChar(grid, r, c - 3, ']');
        setChar(grid, r, c - 2, '^');
        setChar(grid, r, c - 1, '_');
      }
    }
  }

  // Floor bunker: P on right slope (qr)
  // leftCol = left corridor boundary. Bunker row r0, slope descends down to r1.
  // Template (2-column steps, flat floor plate at the bottom):
  //   qrPQR
  //   ppqrS
  //   ppppqr
  //   ppppppp
  function placeBunkerP(grid, r0, r1, leftCol) {
    const cq = leftCol, cr = leftCol + 1, cP = leftCol + 2, cQ = leftCol + 3, cR = leftCol + 4;
    setChar(grid, r0, cq, 'q'); setChar(grid, r0, cr, 'r');
    setChar(grid, r0, cP, 'P'); setChar(grid, r0, cQ, 'Q'); setChar(grid, r0, cR, 'R');
    const offsets = [2, 4];
    for (let i = 0; i < offsets.length && r0 + 1 + i <= r1; i++) {
      const r = r0 + 1 + i;
      const c = leftCol + offsets[i];
      if (c + 1 >= grid[0].length) continue;
      for (let c2 = leftCol; c2 < c; c2++) setChar(grid, r, c2, 'p');
      setChar(grid, r, c, 'q'); setChar(grid, r, c + 1, 'r');
      if (i === 0) setChar(grid, r, c + 2, 'S');
    }
    const rb = r0 + 3;
    if (rb <= r1) {
      for (let c2 = leftCol; c2 <= leftCol + 6 && c2 < grid[0].length; c2++) setChar(grid, rb, c2, 'p');
    }
  }

  // Offset variant of placeBunkerP — identical logic, kept for API consistency
  // with the other *At functions. leftCol is already the offset position.
  function placeBunkerPAt(grid, r0, r1, leftCol) {
    placeBunkerP(grid, r0, r1, leftCol);
  }

  // Floor bunker: U on left slope (st), placed on the RIGHT side of the corridor.
  // rightCol = exclusive right corridor boundary. Bunker row r0, slope descends down to r1.
  // The U is left-facing: the housing is on the left, the st slope descends to the right
  // wall. The bottom row (r1) is the ppppppp floor plate.
  // Template (columns relative to rightCol, right wall at rightCol-1):
  //   UVWstpp
  //   Tstpppp
  //   ppppppp
  function placeBunkerU(grid, r0, r1, rightCol) {
    const leftEdge = rightCol - 7;
    const cU = leftEdge, cV = leftEdge + 1, cW = leftEdge + 2, cs = leftEdge + 3, ct = leftEdge + 4;
    const cP1 = rightCol - 2, cP2 = rightCol - 1;
    setChar(grid, r0, cU, 'U'); setChar(grid, r0, cV, 'V'); setChar(grid, r0, cW, 'W');
    setChar(grid, r0, cs, 's'); setChar(grid, r0, ct, 't');
    setChar(grid, r0, cP1, 'p'); setChar(grid, r0, cP2, 'p');
    for (let r = r0 + 1; r <= r1; r++) {
      const i = r - r0;
      const c = leftEdge + 3 - i * 2;
      if (c < 0 || c + 1 >= grid[0].length) continue;
      for (let c2 = c + 2; c2 <= rightCol - 1; c2++) setChar(grid, r, c2, 'p');
      if (i === 1) {
        setChar(grid, r, leftEdge, 'T');
        setChar(grid, r, leftEdge + 1, 's');
        setChar(grid, r, leftEdge + 2, 't');
      } else {
        for (let c2 = leftEdge; c2 <= rightCol - 1; c2++) setChar(grid, r, c2, 'p');
      }
    }
  }

  // Offset variant of placeBunkerU — rightCol is already the offset position.
  function placeBunkerUAt(grid, r0, r1, rightCol) {
    placeBunkerU(grid, r0, r1, rightCol);
  }

  // ---- Slope carving ----
  // Tiles that are considered "open" on the exposed side of a slope.
  const SLOPE_OPEN_TILES = new Set([' ', '*', '`', 'a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'j', 'k', 'l', 'm', '0', '1', '2', '3', '4']);
  const isOpenForSlope = (ch) => ch !== undefined && SLOPE_OPEN_TILES.has(ch);

  // qr: shifts RIGHT 2 cols/row, p fill on LEFT, open on RIGHT
  function carveQR(grid, r0, r1, startCol) {
    for (let i = 0; i < r1 - r0; i++) {
      const r = r0 + i;
      const c = startCol + i * 2;
      if (c + 1 >= grid[0].length) break;
      // The r tile must be open on its right, otherwise the slope is closed.
      if (c + 2 < grid[0].length && !isOpenForSlope(grid[r][c + 2])) break;
      for (let c2 = 0; c2 < c; c2++) {
        const ch = grid[r][c2];
        if (ch !== ' ' && ch !== 'p') break;
        setChar(grid, r, c2, 'p');
      }
      const cq = grid[r][c], cr = grid[r][c + 1];
      if ((cq !== ' ' && cq !== 'p') || (cr !== ' ' && cr !== 'p')) break;
      // Never create an adjacent identical slope pair (…qrqr…).
      if ((c - 1 >= 0 && grid[r][c - 1] === 'r') || (c + 2 < grid[0].length && grid[r][c + 2] === 'q')) break;
      setChar(grid, r, c, 'q');
      setChar(grid, r, c + 1, 'r');
    }
  }

  // st: shifts LEFT 2 cols/row, p fill on RIGHT, open on LEFT
  function carveST(grid, r0, r1, startCol) {
    for (let i = 0; i < r1 - r0; i++) {
      const r = r0 + i;
      const c = startCol - i * 2;
      if (c < 0 || c + 1 >= grid[0].length) break;
      // The s tile must be open on its left, otherwise the slope is closed.
      if (c - 1 >= 0 && !isOpenForSlope(grid[r][c - 1])) break;
      for (let c2 = c + 2; c2 < grid[0].length; c2++) {
        const ch = grid[r][c2];
        if (ch !== ' ' && ch !== 'p') break;
        setChar(grid, r, c2, 'p');
      }
      const cs = grid[r][c], ct = grid[r][c + 1];
      if ((cs !== ' ' && cs !== 'p') || (ct !== ' ' && ct !== 'p')) break;
      // Never create an adjacent identical slope pair (…stst…).
      if ((c - 1 >= 0 && grid[r][c - 1] === 't') || (c + 2 < grid[0].length && grid[r][c + 2] === 's')) break;
      setChar(grid, r, c, 's');
      setChar(grid, r, c + 1, 't');
    }
  }

  // uv: shifts LEFT 2 cols/row, p fill on LEFT, open on RIGHT
  function carveUV(grid, r0, r1, startCol) {
    for (let i = 0; i < r1 - r0; i++) {
      const r = r0 + i;
      const c = startCol - i * 2;
      if (c < 0 || c + 1 >= grid[0].length) break;
      // The v tile must be open on its right, otherwise the slope is closed.
      if (c + 2 < grid[0].length && !isOpenForSlope(grid[r][c + 2])) break;
      for (let c2 = 0; c2 < c; c2++) {
        const ch = grid[r][c2];
        if (ch !== ' ' && ch !== 'p') break;
        setChar(grid, r, c2, 'p');
      }
      const cu = grid[r][c], cv = grid[r][c + 1];
      if ((cu !== ' ' && cu !== 'p') || (cv !== ' ' && cv !== 'p')) break;
      // Never create an adjacent identical slope pair (…uvuv…).
      if ((c - 1 >= 0 && grid[r][c - 1] === 'v') || (c + 2 < grid[0].length && grid[r][c + 2] === 'u')) break;
      setChar(grid, r, c, 'u');
      setChar(grid, r, c + 1, 'v');
    }
  }

  // wx: shifts RIGHT 2 cols/row, p fill on RIGHT, open on LEFT
  function carveWX(grid, r0, r1, startCol) {
    for (let i = 0; i < r1 - r0; i++) {
      const r = r0 + i;
      const c = startCol + i * 2;
      if (c < 0 || c + 1 >= grid[0].length) break;
      // The w tile must be open on its left, otherwise the slope is closed.
      if (c - 1 >= 0 && !isOpenForSlope(grid[r][c - 1])) break;
      for (let c2 = c + 2; c2 < grid[0].length; c2++) {
        const ch = grid[r][c2];
        if (ch !== ' ' && ch !== 'p') break;
        setChar(grid, r, c2, 'p');
      }
      const cw = grid[r][c], cx = grid[r][c + 1];
      if ((cw !== ' ' && cw !== 'p') || (cx !== ' ' && cx !== 'p')) break;
      // Never create an adjacent identical slope pair (…wxwx…).
      if ((c - 1 >= 0 && grid[r][c - 1] === 'x') || (c + 2 < grid[0].length && grid[r][c + 2] === 'w')) break;
      setChar(grid, r, c, 'w');
      setChar(grid, r, c + 1, 'x');
    }
  }

  // Detect bunker type in a corridor region (only scans the corridor interior).
  // Floor bunkers put their slope/footprint inside the corridor rows; ceiling
  // bunkers do the same.
  function hasFloorBunker(grid, sec) {
    for (let r = sec.r0; r < sec.r1; r++) {
      for (let c = sec.left; c < sec.right; c++) {
        const ch = grid[r][c];
        if (ch === 'P' || ch === 'U') return true;
      }
    }
    return false;
  }
  function hasCeilingBunker(grid, sec) {
    for (let r = sec.r0; r < sec.r1; r++) {
      for (let c = sec.left; c < sec.right; c++) {
        const ch = grid[r][c];
        if (ch === '[' || ch === '\\') return true;
      }
    }
    return false;
  }

  function addSlopesToCorridor(grid, sec, rng) {
    const span = sec.right - sec.left;
    if (span < 20) return;
    const secHeight = sec.r1 - sec.r0;
    if (secHeight < 5) return;

    // Add several slopes per corridor, but only in corridors that contain no
    // bunker at all. This prevents decorative slopes from blocking a bunker or
    // overlapping its slope, and keeps the floor/ceiling orientation per corridor
    // (qr/st on the floor, uv/wx on the ceiling) so the ramps never cross.
    const hasFloor = hasFloorBunker(grid, sec);
    const hasCeiling = hasCeilingBunker(grid, sec);
    if (hasFloor || hasCeiling) return;

    // Determine how much room the corridor ceiling has for uv/wx ramps.
    // The ceiling row is sec.r0 - 1; it should be solid p except for the vertical
    // shaft that feeds into this corridor. Find the open shaft band.
    const ceilRow = sec.r0 - 1;
    let firstOpen = -1;
    let lastOpen = -1;
    if (ceilRow >= 0) {
      for (let cx = sec.left; cx < sec.right; cx++) {
        if (grid[ceilRow][cx] === ' ') {
          if (firstOpen < 0) firstOpen = cx;
          lastOpen = cx;
        }
      }
    }
    // If there is no open band, use a sentinel so the entire ceiling is p.
    if (firstOpen < 0) { firstOpen = sec.right; lastOpen = sec.left - 1; }

    // Each slope orientation is placed at most once per corridor, and a ceiling
    // slope and floor slope on the SAME side must not overlap vertically (2b).
    // sideOccupied tracks the [topRow, bottomRow] ranges already used per side.
    const placedTypes = new Set();
    const sideOccupied = { left: [], right: [] };
    const overlapsSide = (side, a0, a1) =>
      sideOccupied[side].some(([b0, b1]) => a0 - SLOPE_VERTICAL_GAP <= b1 && b0 <= a1 + SLOPE_VERTICAL_GAP);
    const occupySide = (side, a0, a1) => sideOccupied[side].push([a0, a1]);
    // Random solid-wall margin between a slope and the level edge (req 4).
    const edgeMargin = () =>
      SLOPE_EDGE_MARGIN_MIN + Math.floor(rng() * (SLOPE_EDGE_MARGIN_MAX - SLOPE_EDGE_MARGIN_MIN + 1));

    const numSlopes = 2 + Math.floor(rng() * 3);
    for (let s = 0; s < numSlopes; s++) {
      const desiredLen = 2 + Math.floor(rng() * 4);
      const maxFloorLen = Math.max(2, Math.min(desiredLen, secHeight - 2, Math.floor((span - 4) / 2)));
      const maxCeilLen = Math.max(2, Math.min(desiredLen, secHeight - 1, Math.floor((span - 4) / 2)));

      // Ceiling ramps: start at the corridor ceiling row (sec.r0) and ensure
      // the p ceiling above (sec.r0 - 1) is solid across the ramp width.
      // uv on the left, wx on the right.
      let placed = false;
      const tryCeiling = (type) => {
        if (placedTypes.has(type)) return false;
        const margin = edgeMargin();
        if (type === 'uv') {
          // The p ceiling above the ramp must cover columns 0..startCol+1.
          let startCol = sec.left + Math.min(desiredLen * 2 + 2, Math.floor(span / 2));
          startCol = Math.min(startCol, firstOpen - 2);
          let len = Math.max(2, Math.min(desiredLen, Math.floor(startCol / 2) + 1, maxCeilLen));
          // Keep the lowest column (startCol - 2*(len-1)) margin cols off the left edge.
          while (len > 2 && startCol - 2 * (len - 1) < sec.left + margin) len--;
          if (startCol < 2 || startCol + 1 >= firstOpen || len < 2) return false;
          if (startCol + 1 >= sec.right) return false;
          if (startCol - 2 * (len - 1) < sec.left + margin) return false;
          if (overlapsSide('left', sec.r0, sec.r0 + len - 1)) return false;
          carveUV(grid, sec.r0, sec.r0 + len, startCol);
          occupySide('left', sec.r0, sec.r0 + len - 1);
          placedTypes.add(type);
          return true;
        } else {
          // The p ceiling above the ramp must cover columns startCol..right-1.
          let startCol = sec.right - 3 - Math.min(desiredLen * 2 + 2, Math.floor(span / 2));
          startCol = Math.max(startCol, lastOpen + 1);
          let len = Math.max(2, Math.min(desiredLen, Math.floor((sec.right - 1 - startCol) / 2) + 1, maxCeilLen));
          // Keep the lowest column margin cols off the right edge.
          while (len > 2 && startCol + 2 * (len - 1) + 1 > sec.right - 1 - margin) len--;
          if (startCol < sec.left || startCol <= lastOpen || len < 2) return false;
          if (startCol + 2 * (len - 1) + 1 >= sec.right) return false;
          if (startCol + 2 * (len - 1) + 1 > sec.right - 1 - margin) return false;
          if (overlapsSide('right', sec.r0, sec.r0 + len - 1)) return false;
          carveWX(grid, sec.r0, sec.r0 + len, startCol);
          occupySide('right', sec.r0, sec.r0 + len - 1);
          placedTypes.add(type);
          return true;
        }
      };

      // Floor ramps: generated one row lower (bottom at sec.r1 - 1) so the slope
      // sits directly on the corridor floor with solid 'pp' below, instead of
      // leaving a thin one-row plate (req 3).
      const tryFloor = (type) => {
        if (placedTypes.has(type)) return false;
        const len = Math.min(desiredLen, maxFloorLen);
        if (len < 2) return false;
        const margin = edgeMargin();
        const startRow = sec.r1 - len;
        if (startRow < sec.r0 + 1) return false;
        const side = type === 'qr' ? 'left' : 'right';
        if (overlapsSide(side, startRow, startRow + len - 1)) return false;
        if (type === 'qr') {
          const startCol = sec.left + margin;
          if (startCol + 2 * (len - 1) + 1 >= sec.right) return false;
          carveQR(grid, startRow, startRow + len, startCol);
        } else {
          const startCol = sec.right - 3 - margin;
          if (startCol - 2 * (len - 1) < sec.left) return false;
          carveST(grid, startRow, startRow + len, startCol);
        }
        occupySide(side, startRow, startRow + len - 1);
        placedTypes.add(type);
        return true;
      };

      // Choose orientation and side. If one fails, try the other side.
      if (rng() < 0.5) {
        placed = tryCeiling('uv') || tryCeiling('wx');
        if (!placed) placed = tryFloor('qr') || tryFloor('st');
      } else {
        placed = tryFloor('qr') || tryFloor('st');
        if (!placed) placed = tryCeiling('uv') || tryCeiling('wx');
      }
      // If nothing could be placed, move on.
      if (!placed) continue;
    }
  }

  // ---- Right-side surface hill ----
  // Extend the level by 100 columns to the right, filled with a solid wall
  // whose top edge forms a randomly sloped surface (hills and valleys of
  // flat `p` plateaus connected by `q/r` down steps and `s/t` up steps).
  // Also remove the left/right outer p walls down to the floor surface so the
  // left edge and the right end of the new hill match.
  function addRightSurfaceHill(grid, width, height, rng) {
    const EXT_WIDTH = 100;

    // Find the floor surface row by looking for the first row where the left
    // wall (col 0) is p and the cell directly inside it (col 1) is also p.
    let floorRow = height - FLOOR_ROWS;
    for (let r = 0; r < height; r++) {
      if (grid[r][0] === 'p' && grid[r][1] === 'p') {
        floorRow = r;
        break;
      }
    }

    // Identify rows that hold H/G doors – these must keep their left/right wall
    // contact so the slider spans wall-to-wall.
    const doorRows = new Set();
    for (let r = 0; r < height; r++) {
      if (grid[r].includes('H') || grid[r].includes('G')) doorRows.add(r);
    }

    // Build a 50-segment surface profile using st/qr slopes and flat p
    // plateaus.  The grammar never places st and qr next to each other;
    // a flat p plateau is always between slope directions.
    const segments = EXT_WIDTH / 2;
    const tiles = new Array(segments).fill('p');
    const heights = new Array(segments).fill(floorRow);
    const minSurface = SKY_ROWS + 2;

    let h = floorRow;
    let state = 'floor';
    tiles[0] = 'p';
    heights[0] = h;

    for (let i = 1; i < segments; i++) {
      const last = i === segments - 1;
      const choices = [];
      if (state === 'floor') {
        if (h <= height - 1 && !doorRows.has(h)) choices.push('p');
        if (h - 1 >= minSurface - 1 && !doorRows.has(h - 1)) choices.push('s');
        if (h <= height - 2 && !doorRows.has(h)) choices.push('q');
      } else if (state === 'up') {
        if (h - 1 >= minSurface - 1 && !doorRows.has(h - 1)) choices.push('s');
        if (h <= height - 1 && !doorRows.has(h)) choices.push('p');
      } else if (state === 'down') {
        if (h <= height - 2 && !doorRows.has(h)) choices.push('q');
        if (h <= height - 1 && !doorRows.has(h)) choices.push('p');
      }
      if (last) {
        const slopeChoices = choices.filter(t => t !== 'p');
        if (slopeChoices.length) {
          choices.length = 0;
          choices.push(...slopeChoices);
        }
      }
      let pick = choices[Math.floor(rng() * choices.length)] || 'p';
      tiles[i] = pick;
      if (pick === 's') {
        h--;
        state = 'up';
      } else if (pick === 'q') {
        state = 'down';
      } else {
        state = 'floor';
      }
      heights[i] = h;
      if (pick === 'q') h++;
    }

    // Choose where to cut the extension for the later "move rightmost columns
    // to the front" rotation. The cut must land on a flat 'p' plateau where
    // both segments share the same height, otherwise the two columns that
    // become the new col-0/col-(width-1) wraparound edges won't match for
    // every row (sky vs wall mismatch at that row's surface). We search near
    // the ideal target segment (10 segments = 20 columns from the end) for
    // the nearest such safe boundary.
    const targetCutSegment = segments - (MOVE_COLUMNS_TARGET / 2);
    let cutSegment = null;
    for (let d = 0; d < segments; d++) {
      for (const k of [targetCutSegment - d, targetCutSegment + d]) {
        if (k < 1 || k > segments - 1) continue;
        if (tiles[k - 1] === 'p' && tiles[k] === 'p' && heights[k - 1] === heights[k]) {
          cutSegment = k;
          break;
        }
      }
      if (cutSegment !== null) break;
    }
    // Fallback: force a flat plateau at the target cut if none was found.
    if (cutSegment === null) {
      cutSegment = Math.min(Math.max(targetCutSegment, 1), segments - 1);
      tiles[cutSegment - 1] = 'p';
      tiles[cutSegment] = 'p';
      heights[cutSegment] = heights[cutSegment - 1];
    }
    const moveColumns = (segments - cutSegment) * 2;

    // Ensure the right edge ends with a slope, not a vertical p wall.
    if (tiles[segments - 1] === 'p') {
      if ((state === 'floor' || state === 'up') && h - 1 >= minSurface - 1 && !doorRows.has(h - 1)) {
        tiles[segments - 1] = 's';
        h--;
        heights[segments - 1] = h;
      } else if ((state === 'floor' || state === 'down') && h <= height - 2 && !doorRows.has(h)) {
        tiles[segments - 1] = 'q';
        heights[segments - 1] = h;
      }
    }

    // Remove the left and right outer p walls above the surface so the left
    // edge matches the right edge surface height and the extension connects
    // cleanly. The original right edge is exposed up to the floor row; the left
    // edge follows the final right edge surface height.
    const rightEdgeSurface = heights[segments - 1];
    for (let r = 0; r < height; r++) {
      if (!doorRows.has(r) && grid[r][0] === 'p' && r < rightEdgeSurface) grid[r][0] = ' ';
      if (!doorRows.has(r) && grid[r][width - 1] === 'p' && r < floorRow) grid[r][width - 1] = ' ';
    }

    // Create the extension: space above the surface, p wall below it.
    const ext = [];
    for (let r = 0; r < height; r++) {
      ext.push(new Array(EXT_WIDTH).fill('p'));
    }

    for (let i = 0; i < segments; i++) {
      const c0 = i * 2;
      const h = heights[i];

      // Clear the sky above the surface.
      for (let r = 0; r < h; r++) {
        ext[r][c0] = ' ';
        ext[r][c0 + 1] = ' ';
      }

      // Place the surface tile pair: pp, st, or qr.
      const tile = tiles[i];
      if (tile === 's') {
        ext[h][c0] = 's';
        ext[h][c0 + 1] = 't';
      } else if (tile === 'q') {
        ext[h][c0] = 'q';
        ext[h][c0 + 1] = 'r';
      } else {
        ext[h][c0] = 'p';
        ext[h][c0 + 1] = 'p';
      }
    }

    // Door rows must be a solid wall across the entire new width.
    for (const r of doorRows) {
      for (let c = 0; c < EXT_WIDTH; c++) ext[r][c] = 'p';
    }

    // Append the extension to the existing grid and return the new width.
    for (let r = 0; r < height; r++) {
      grid[r].push(...ext[r]);
    }

    // Fill any enclosed air pockets inside the extension with p. The extension
    // is a wall; only open space reachable from the player's start '*' should
    // remain ' '. Surface overhangs can trap unreachable pockets otherwise.
    let start = null;
    for (let r = 0; r < height; r++) {
      const c = grid[r].indexOf('*');
      if (c !== -1) { start = [r, c]; break; }
    }
    if (start) {
      const newWidth = width + EXT_WIDTH;
      const seen = new Set([`${start[0]},${start[1]}`]);
      const q = [start];
      while (q.length > 0) {
        const [r, c] = q.pop();
        for (const [dr, dc] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
          const nr = r + dr, nc = c + dc;
          if (nr < 0 || nr >= height || nc < 0 || nc >= newWidth) continue;
          const ch = grid[nr][nc];
          if (ch !== ' ' && ch !== '*') continue;
          const k = `${nr},${nc}`;
          if (seen.has(k)) continue;
          seen.add(k);
          q.push([nr, nc]);
        }
      }
      for (let r = 0; r < height; r++) {
        for (let c = width; c < newWidth; c++) {
          if (grid[r][c] === ' ' && !seen.has(`${r},${c}`)) {
            grid[r][c] = 'p';
          }
        }
      }
    }

    return { width: width + EXT_WIDTH, moveColumns };
  }

  // ---- Main generation ----
  // Strategy: carve a continuous winding path from sky to pod chamber.
  // All corridors span wall-to-wall (col 1 to width-2).
  // Vertical shafts are narrower but always overlap with corridors above and below.
  // The final corridor connects directly to the pod chamber.
  function generateRandomLevel(opts) {
    opts = opts || {};
    let width = opts.width || DEFAULT_WIDTH;
    // The requested width already includes the 100px right surface hill;
    // subtract it so the generated world is the interior size and the hill
    // extension restores the requested final width.
    width = Math.max(width - RIGHT_SURFACE_HILL_WIDTH, MIN_SHAFT_WIDTH + 10);
    const height = opts.height || DEFAULT_HEIGHT;
    const seed = opts.seed || (Math.random() * 1e9) | 0;
    const hasBunkers = opts.bunkers != null || opts.maxBunkers != null;
    const hasFuel = opts.fuel != null || opts.maxFuel != null;
    const maxBunkers = hasBunkers ? parseInt(opts.bunkers != null ? opts.bunkers : opts.maxBunkers, 10) : 5;
    const maxFuel = hasFuel ? parseInt(opts.fuel != null ? opts.fuel : opts.maxFuel, 10) : 6;
    // If a count is given without a chance, default to 1.0 so we try to place the
    // exact requested number. If no count is given, use the legacy random defaults.
    const bunkerChance = opts.bunkerChance != null ? parseFloat(opts.bunkerChance) : (hasBunkers ? 1.0 : 0.5);
    const fuelChance = opts.fuelChance != null ? parseFloat(opts.fuelChance) : (hasFuel ? 1.0 : 0.55);
    const rng = mulberry32(seed);

    const grid = makeGrid(width, height, 'p');
    const corLeft = 1;            // first open column in corridors
    const corRight = width - 1;   // last open column + 1 (exclusive)

    // 1. Sky (open space at top). Open the full width (col 0..width-1) so the
    // topmost rows have no p walls at the edges and the horizontal wraparound
    // lines up (space on both edges).
    for (let r = 0; r < SKY_ROWS; r++) setRange(grid, r, 0, width, ' ');

    // 2. Start position
    const startCol = 5 + Math.floor(rng() * (width - 10));
    setChar(grid, 5, startCol, '*');

    // 3. Build winding path: alternating full-width corridors and vertical shafts
    const corridors = [];
    const shafts = [];
    let curRow = SKY_ROWS;
    const podReserve = 15; // rows reserved for pod chamber at bottom

    while (curRow < height - FLOOR_ROWS - podReserve) {
      // --- Horizontal corridor (full width) ---
      // At least MIN_CORRIDOR_HEIGHT rows, randomly up to +CORRIDOR_RANDOM_EXTRA_HEIGHT.
      const corHeight = MIN_CORRIDOR_HEIGHT + Math.floor(rng() * (CORRIDOR_RANDOM_EXTRA_HEIGHT + 1));
      const corEnd = Math.min(curRow + corHeight, height - FLOOR_ROWS - podReserve);
      for (let r = curRow; r < corEnd; r++) corridor(grid, r, corLeft, corRight);
      corridors.push({ r0: curRow, r1: corEnd, left: corLeft, right: corRight });
      curRow = corEnd;

      if (curRow >= height - FLOOR_ROWS - podReserve) break;

      // --- Vertical shaft (narrow, within corridor span) ---
      const shaftWidth = MIN_SHAFT_WIDTH + Math.floor(rng() * 3); // 5-7
      const margin = corRight - corLeft - shaftWidth - 2;
      const shaftLeft = corLeft + 1 + Math.floor(rng() * Math.max(1, margin));
      const shaftRight = shaftLeft + shaftWidth;
      const shaftHeight = 5 + Math.floor(rng() * 5); // 5-9
      const shaftEnd = Math.min(curRow + shaftHeight, height - FLOOR_ROWS - podReserve);
      vcorridor(grid, curRow, shaftEnd, shaftLeft, shaftRight);
      shafts.push({ r0: curRow, r1: shaftEnd, left: shaftLeft, right: shaftRight });
      curRow = shaftEnd;
    }

    // 4. Final corridor connecting to pod chamber (full width)
    const finalCorStart = curRow;
    const podRow = height - FLOOR_ROWS - 5;
    const podCol = Math.floor(width / 2) - 1;
    // Carve final corridor down to pod chamber
    for (let r = finalCorStart; r < podRow - 2; r++) corridor(grid, r, corLeft, corRight);
    corridors.push({ r0: finalCorStart, r1: podRow - 2, left: corLeft, right: corRight });

    // 5. Pod chamber
    for (let r = podRow - 3; r < Math.min(podRow + 4, height - FLOOR_ROWS); r++)
      corridor(grid, r, podCol - 5, podCol + 7);
    placePod(grid, podRow, podCol);
    // Ensure cell above pod is open
    setChar(grid, podRow - 1, podCol, ' ');
    setChar(grid, podRow - 1, podCol + 1, ' ');
    // Ensure wall below pod holder for wall contact
    setChar(grid, podRow + 3, podCol, 'p');
    setChar(grid, podRow + 3, podCol + 1, 'p');

    // 7. Floor
    for (let r = height - FLOOR_ROWS; r < height; r++) setRange(grid, r, 0, width, 'p');

    // Re-open corridor boundary rows before placing features on them.
    // Features (ceiling bunkers, reactor bottom, fuel bc row, door) sit on sec.r0 or sec.r1-1.
    for (const sec of corridors) {
      corridor(grid, sec.r0, sec.left, sec.right);
      corridor(grid, sec.r1 - 1, sec.left, sec.right);
    }

    // 8. Place features along corridors
    let fuelCount = 0;
    let bunkerCount = 0;
    let hasReactor = false;
    let hasDoor = false;

    // Track occupied columns per corridor row to avoid overlapping features.
    // Each corridor gets a Set of "used" column ranges so multiple bunkers/fuel
    // can be placed in the same corridor at different horizontal positions.
    function markUsedCols(sec, startCol, endCol) {
      if (!sec._usedCols) sec._usedCols = new Set();
      for (let c = startCol; c <= endCol; c++) sec._usedCols.add(c);
    }
    function isColRangeFree(sec, startCol, endCol) {
      if (!sec._usedCols) return true;
      for (let c = startCol; c <= endCol; c++) if (sec._usedCols.has(c)) return false;
      return true;
    }

    // Bunker footprint widths for spacing calculations.
    const BUNKER_BRACKET_WIDTH = 10;  // [ ceiling bunker: cols 0..9
    const BUNKER_BACKSLASH_WIDTH = 10; // \ ceiling bunker
    const BUNKER_P_WIDTH = 7;          // P floor bunker: cols left..left+6
    const BUNKER_U_WIDTH = 7;          // U floor bunker: cols right-7..right-1
    const FUEL_WIDTH = 2;              // fuel depot: 2 cols
    const FEATURE_SPACING = 3;         // min gap between features in same corridor

    for (const sec of corridors) {
      const span = sec.right - sec.left;
      if (span < 10) continue;
      const secHeight = sec.r1 - sec.r0;

      // --- Fuel: try to place multiple fuel depots per corridor ---
      // Scan from left to right, trying positions until we hit maxFuel or run out of space.
      // Fuel containers can be placed directly adjacent (every 2 tiles) if needed.
      if (span >= 16) {
        const fuelR = sec.r1 - 2;
        if (fuelR >= 3 && fuelR + 2 < grid.length) {
          for (let fc = sec.left + 7; fc < sec.right - 8 && fuelCount < maxFuel; fc += FUEL_WIDTH) {
            if (fc + 1 >= sec.right - 1) break;
            if (!isColRangeFree(sec, fc, fc + 1)) continue;
            // Check chance (skip chance check if count was explicitly requested)
            if (rng() >= fuelChance) continue;
            let clear = true;
            for (let dy = 1; dy <= 2; dy++)
              for (let dx = 0; dx <= 1; dx++)
                if (isWallTile(grid, fuelR - dy, fc + dx)) clear = false;
            if (isWallTile(grid, fuelR, fc) || isWallTile(grid, fuelR, fc + 1) ||
                isWallTile(grid, fuelR + 1, fc) || isWallTile(grid, fuelR + 1, fc + 1))
              clear = false;
            if (!isWallTile(grid, fuelR + 2, fc) || !isWallTile(grid, fuelR + 2, fc + 1))
              clear = false;
            if (clear) {
              placeFuel(grid, fuelR, fc);
              markUsedCols(sec, fc, fc + 1);
              fuelCount++;
            }
          }
        }
      }

      // --- Bunkers: try to place multiple bunkers per corridor ---
      // Alternate between ceiling and floor, left and right sides, scanning across the corridor.
      // Continue until we hit maxBunkers or run out of space in the corridor.
      const maxAttemptsPerCorridor = Math.ceil(maxBunkers / Math.max(1, corridors.length)) + 10;
      let attemptsInThisCorridor = 0;
      while (bunkerCount < maxBunkers && attemptsInThisCorridor < maxAttemptsPerCorridor) {
        attemptsInThisCorridor++;
        if (rng() >= bunkerChance) continue;

        let placed = false;
        const mount = rng() < 0.5 ? 'ceiling' : 'floor';

        if (mount === 'ceiling') {
          // Try ceiling bunkers at different horizontal offsets.
          // Ceiling bracket ([) on left side, backslash (\) on right side.
          const side = rng() < 0.5 ? 'left' : 'right';
          if (sec.r0 > SKY_ROWS && sec.r0 + 4 < sec.r1 && secHeight >= 5) {
            const r0 = sec.r0;
            const r1 = sec.r0 + 2;
            if (side === 'left') {
              // Try bracket bunker at various offsets from the left wall.
              const offset = Math.floor(rng() * Math.max(1, span - BUNKER_BRACKET_WIDTH - FEATURE_SPACING));
              const startCol = sec.left + offset;
              if (startCol + BUNKER_BRACKET_WIDTH < sec.right &&
                  isColRangeFree(sec, startCol, startCol + BUNKER_BRACKET_WIDTH)) {
                // Check ceiling above is solid p
                let ceilOk = true;
                for (let c = startCol; c <= startCol + 9; c++) {
                  if (c >= grid[0].length || grid[r0 - 1][c] !== 'p') ceilOk = false;
                }
                if (ceilOk) {
                  // Place bracket bunker at offset
                  placeBunkerBracketAt(grid, r0, r1, startCol);
                  markUsedCols(sec, startCol, startCol + BUNKER_BRACKET_WIDTH);
                  bunkerCount++;
                  placed = true;
                }
              }
            } else {
              // Try backslash bunker at various offsets from the right wall.
              const offset = Math.floor(rng() * Math.max(1, span - BUNKER_BACKSLASH_WIDTH - FEATURE_SPACING));
              const endCol = sec.right - 1 - offset;
              const startCol = endCol - BUNKER_BACKSLASH_WIDTH + 1;
              if (startCol >= sec.left &&
                  isColRangeFree(sec, startCol, endCol)) {
                let ceilOk = true;
                for (let c = startCol; c <= endCol; c++) {
                  if (c >= grid[0].length || grid[r0 - 1][c] !== 'p') ceilOk = false;
                }
                if (ceilOk) {
                  placeBunkerBackslashAt(grid, r0, r1, endCol + 1);
                  markUsedCols(sec, startCol, endCol);
                  bunkerCount++;
                  placed = true;
                }
              }
            }
          }
        }

        if (!placed) {
          // Try floor bunkers at different horizontal offsets.
          const side = rng() < 0.5 ? 'left' : 'right';
          const floorRow = sec.r1 + 1;
          if (floorRow < grid.length && secHeight >= 4) {
            if (side === 'left') {
              // P bunker: needs 7 cols, floor must be solid p below.
              const offset = Math.floor(rng() * Math.max(1, span - BUNKER_P_WIDTH - FEATURE_SPACING));
              const startCol = sec.left + offset;
              if (startCol + BUNKER_P_WIDTH < sec.right &&
                  isColRangeFree(sec, startCol, startCol + BUNKER_P_WIDTH)) {
                let floorOk = true;
                for (let c = startCol; c <= startCol + 6; c++) {
                  if (grid[floorRow][c] !== 'p') { floorOk = false; break; }
                }
                if (floorOk) {
                  placeBunkerPAt(grid, sec.r1 - 3, sec.r1, startCol);
                  markUsedCols(sec, startCol, startCol + BUNKER_P_WIDTH);
                  bunkerCount++;
                  placed = true;
                }
              }
            } else {
              // U bunker: needs 7 cols from the right.
              const offset = Math.floor(rng() * Math.max(1, span - BUNKER_U_WIDTH - FEATURE_SPACING));
              const endCol = sec.right - 1 - offset;
              const startCol = endCol - BUNKER_U_WIDTH + 1;
              if (startCol >= sec.left &&
                  isColRangeFree(sec, startCol, endCol)) {
                let floorOk = true;
                for (let c = startCol; c <= endCol; c++) {
                  if (grid[floorRow][c] !== 'p') { floorOk = false; break; }
                }
                if (floorOk && secHeight >= 3) {
                  placeBunkerUAt(grid, sec.r1 - 2, sec.r1, endCol + 1);
                  markUsedCols(sec, startCol, endCol);
                  bunkerCount++;
                  placed = true;
                }
              }
            }
          }
        }
      }

      // Reactor: once, placed on the corridor floor wall
      if (!hasReactor && rng() < 0.4 && span > 15 && secHeight >= 4) {
        const rc = sec.left + 5 + Math.floor(rng() * (span - 14));
        const rr = sec.r1 - 3;
        if (rr >= sec.r0 && rc + 3 < sec.right - 2) {
          placeReactor(grid, rr, rc);
          hasReactor = true;
        }
      }

    }

    // Doors/sliders belong in the vertical shafts (the passages between caves),
    // not across a horizontal cave corridor. Place one 3-row-thick horizontal
    // slider spanning a shaft, with open passage above and below and a button
    // on the shaft wall.
    for (const sh of shafts) {
      if (hasDoor) break;
      const shHeight = sh.r1 - sh.r0;
      const shWidth = sh.right - sh.left;
      // Need room for the '#' separator (r0+1), open rows around a 3-row door,
      // and the door must be wide enough for H..p..G.
      if (shHeight < 8 || shWidth < 4) continue;
      const doorR = sh.r0 + Math.floor(shHeight / 2);
      // H at the left shaft wall column, G at the right shaft wall column so the
      // door fills the shaft opening; cols outside the shaft are already solid p.
      placeDoorRow(grid, doorR, sh.left, sh.right - 1);

      // Buttons: one above and one below the slider so it can be opened from both
      // sides. The button is on a wall cell with the matching marker in the row
      // directly below: N/O for a right-facing wall, L/M for a left-facing wall.
      // Prefer the right-facing wall (right side of the shaft, column sh.right);
      // fall back to the left-facing wall (left side, column sh.left - 1).
      const rightFacingCol = sh.right;
      const leftFacingCol = sh.left - 1;
      const canUseRight = rightFacingCol < grid[0].length - 1;
      const canUseLeft = leftFacingCol >= 1;
      const [btnChar, markChar, wallCol] =
        canUseRight ? ['N', 'O', rightFacingCol] : ['L', 'M', leftFacingCol];
      const btnUpperRow = doorR - 2;
      const btnLowerRow = doorR + 2;
      if (btnUpperRow >= 0 && btnUpperRow + 1 < grid.length) {
        setChar(grid, btnUpperRow, wallCol, btnChar);
        setChar(grid, btnUpperRow + 1, wallCol, markChar);
      }
      if (btnLowerRow >= 0 && btnLowerRow + 1 < grid.length) {
        setChar(grid, btnLowerRow, wallCol, btnChar);
        setChar(grid, btnLowerRow + 1, wallCol, markChar);
      }
      hasDoor = true;
    }

    // Ensure at least one fuel depot
    if (fuelCount === 0 && corridors.length > 0) {
      const sec = corridors[0];
      const fc = sec.left + 7;
      const fuelR = sec.r1 - 2;
      if (fuelR >= 3 && fuelR + 2 < grid.length) {
        let clear = true;
        for (let dy = 1; dy <= 2; dy++)
          for (let dx = 0; dx <= 1; dx++)
            if (isWallTile(grid, fuelR - dy, fc + dx)) clear = false;
        // Fuel cells themselves must be empty
        if (isWallTile(grid, fuelR, fc) || isWallTile(grid, fuelR, fc + 1) ||
            isWallTile(grid, fuelR + 1, fc) || isWallTile(grid, fuelR + 1, fc + 1))
          clear = false;
        if (!isWallTile(grid, fuelR + 2, fc) || !isWallTile(grid, fuelR + 2, fc + 1))
          clear = false;
        if (clear) placeFuel(grid, fuelR, fc);
      }
    }

    // Ensure at least one reactor, placed on the corridor floor wall
    if (!hasReactor && corridors.length > 1) {
      const sec = corridors[1];
      const rc = sec.left + 5;
      const rr = sec.r1 - 3;
      const height = sec.r1 - sec.r0;
      if (rr >= sec.r0 && height >= 4 && rc + 3 < sec.right - 2) placeReactor(grid, rr, rc);
    }

    // 9. Add extra decorative slopes to corridors without bunkers.
    // Run after feature placement so the safe carvers can avoid overwriting features.
    for (const sec of corridors) {
      addSlopesToCorridor(grid, sec, rng);
    }

    // 10. Ensure slope continuity: qr/st need wall below, uv/wx need wall above.
    // Fill a solid p ceiling/floor across the whole width of each ramp, not just
    // below the slope tiles. This prevents open pockets from forming under/over
    // the p-fill part of the ramp while preserving the open side of the slope.
    // Only fill open ' ' cells, never overwrite features, doors, start or pod.
    // The validator requires pp directly below qr/st and above uv/wx, so we
    // unconditionally fill any open cells in those rows.
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width - 1; x++) {
        const ch = grid[y][x];
        const ch2 = grid[y][x + 1];
        if (ch === 'q' && ch2 === 'r') {
          // qr floor ramp: p floor below from left wall to r column.
          const c = x + 1;
          if (y + 1 < height) {
            for (let c2 = 0; c2 <= c; c2++) {
              if (grid[y + 1][c2] === ' ') {
                setChar(grid, y + 1, c2, 'p');
              }
            }
          }
        } else if (ch === 's' && ch2 === 't') {
          // st floor ramp: p floor below from s column to right wall.
          if (y + 1 < height) {
            for (let c2 = x; c2 < width; c2++) {
              if (grid[y + 1][c2] === ' ') {
                setChar(grid, y + 1, c2, 'p');
              }
            }
          }
        } else if (ch === 'u' && ch2 === 'v') {
          // uv ceiling ramp: p ceiling above from left wall to v column.
          const c = x + 1;
          if (y - 1 >= 0) {
            for (let c2 = 0; c2 <= c; c2++) {
              if (grid[y - 1][c2] === ' ') {
                setChar(grid, y - 1, c2, 'p');
              }
            }
          }
        } else if (ch === 'w' && ch2 === 'x') {
          // wx ceiling ramp: p ceiling above from w column to right wall.
          if (y - 1 >= 0) {
            for (let c2 = x; c2 < width; c2++) {
              if (grid[y - 1][c2] === ' ') {
                setChar(grid, y - 1, c2, 'p');
              }
            }
          }
        }
      }
    }

    // 10. Respawn-area separators and stars.
    // Run after all decoration and slope continuity so the stars can see the
    // final obstacles (sliders, slopes, walls). Each shaft gets a '#' row and a
    // '*' below it; every shaft from the second one also gets a '*' above it.
    // The star can be pushed into the adjacent corridor, not necessarily inside
    // the shaft: we search within the shaft column range for a free cell that
    // has MIN_RESPAWN_OBSTACLE_DISTANCE_BELOW free rows below it. For the
    // below-star we also keep one free row between the star and the obstacle
    // above it (e.g. a slider) so the respawn point is two rows below the
    // barrier and not directly under it.
    function freeRowsBelow(r, c) {
      let count = 0;
      for (let y = r + 1; y < grid.length; y++) {
        if (isObstacleTile(grid, y, c)) break;
        count++;
      }
      return count;
    }
    function findSafeStarCell(startR, minC, maxC, direction) {
      // Build candidate columns ordered by distance to the shaft center so the
      // star is placed in the middle of the passage instead of against a wall.
      const center = Math.floor((minC + maxC) / 2);
      const candidates = [];
      for (let c = minC; c <= maxC; c++) {
        candidates.push({ c, dist: Math.abs(c - center) });
      }
      candidates.sort((a, b) => a.dist - b.dist);

      let r = startR;
      while (r >= 0 && r < grid.length) {
        for (const { c } of candidates) {
          if (grid[r][c] !== ' ') continue;
          if (freeRowsBelow(r, c) < MIN_RESPAWN_OBSTACLE_DISTANCE_BELOW) continue;
          // For the star below the separator, ensure there is one free row
          // between the star and the obstacle above it (slider, etc.).
          if (direction > 0 && isObstacleTile(grid, r - 1, c)) continue;
          // Horizontal clearance: at least MIN_RESPAWN_HORIZONTAL_CLEARANCE
          // free cells to the left and right before any obstacle or wall.
          let ok = true;
          for (let d = 1; d <= MIN_RESPAWN_HORIZONTAL_CLEARANCE; d++) {
            if (isObstacleTile(grid, r, c - d) || isObstacleTile(grid, r, c + d)) {
              ok = false;
              break;
            }
          }
          if (!ok) continue;
          return { r, c };
        }
        r += direction;
      }
      return null;
    }
    const shaftCount = shafts.length;
    for (let i = 0; i < shaftCount; i++) {
      const sh = shafts[i];
      const hashRow = sh.r0 + 1;
      if (hashRow >= sh.r1) continue;
      for (let c = sh.left; c < sh.right; c++) setChar(grid, hashRow, c, '#');
      const minC = sh.left;
      const maxC = sh.right - 1;
      const below = findSafeStarCell(hashRow + 1, minC, maxC, +1);
      if (below) setChar(grid, below.r, below.c, '*');
      if (i > 0) {
        const above = findSafeStarCell(hashRow - 1, minC, maxC, -1);
        if (above) setChar(grid, above.r, above.c, '*');
      }
    }

    // 11. Extend level with a 100-column right-side surface hill and
    // remove the left/right edge p walls down to the floor surface.
    const hillResult = addRightSurfaceHill(grid, width, height, rng);
    width = hillResult.width;

    // 12. Move the rightmost columns of each row to the beginning so the
    // generated right wall/surface appears on the left side. The cut point
    // (hillResult.moveColumns) was chosen by addRightSurfaceHill to land on
    // a safe flat plateau so the new wraparound edges match.
    const MOVE_COLUMNS = hillResult.moveColumns;
    for (let r = 0; r < grid.length; r++) {
      const row = grid[r];
      const split = row.length - MOVE_COLUMNS;
      grid[r] = [...row.slice(split), ...row.slice(0, split)];
    }

    // 13. Build .def text
    const lines = [];
    // Header
    lines.push(width.toString());
    lines.push(height.toString());
    lines.push(START_HEIGHT.toString());
    lines.push(EMPTY_SPACE_HEIGHT.toString());
    lines.push(BEDROCK_HEIGHT.toString());
    lines.push('  0  84 164 ; background/tractor (wall color)');
    lines.push('164   0   0 ; gun/reactor/stand (bunker color)');
    lines.push('  0 164   0 ; pod/blip (pod color)');
    lines.push('  0 164 164 ; text (text color)');
    lines.push('164  84  84 ; shield (shield color)');
    // Grid
    for (const row of grid) lines.push(row.join(''));

    return lines.join('\n');
  }

  // ---- Validation loop ----
  async function loadValidator() {
    if (typeof window !== 'undefined') {
      return await import('/src/levels/level-validator.js');
    } else {
      const url = new URL('../../src/levels/level-validator.js', import.meta.url);
      return await import(url.href);
    }
  }

  async function generateValidRandomLevel(opts) {
    const validator = await loadValidator();
    const maxAttempts = 1000;
    const bestEffortThreshold = 200;
    let baseSeed = (opts && opts.seed) || null;
    let result = { errors: [] };
    let bestEffort = null;

    for (let i = 0; i < maxAttempts; i++) {
      const callOpts = Object.assign({}, opts);
      if (baseSeed !== null) callOpts.seed = baseSeed + i;

      const defText = generateRandomLevel(callOpts);
      result = validator.validateDef(defText);
      if (result.valid) {
        let matchOk = true;
        if (opts.bunkers != null && opts.bunkerChance == null) {
          if (result.inventory.bunkers !== parseInt(opts.bunkers, 10)) matchOk = false;
        }
        if (opts.fuel != null && opts.fuelChance == null) {
          if (result.inventory.fuel !== parseInt(opts.fuel, 10)) matchOk = false;
        }
        if (opts.requireDoor && result.inventory.doors_H === 0) {
          matchOk = false;
        }
        if (opts.rejectWarnings && result.warnings.length > 0) {
          matchOk = false;
        }
        if (matchOk) {
          console.log(`[GEN_OK] Valid level generated on attempt ${i + 1}`);
          return defText;
        }
        // Track best effort for fallback
        if (!bestEffort) {
          bestEffort = { defText, bunkers: result.inventory.bunkers, fuel: result.inventory.fuel };
        } else {
          const targetBunkers = opts.bunkers != null ? parseInt(opts.bunkers, 10) : null;
          const targetFuel = opts.fuel != null ? parseInt(opts.fuel, 10) : null;
          const currDiff = Math.abs(bestEffort.bunkers - (targetBunkers ?? 0)) + Math.abs(bestEffort.fuel - (targetFuel ?? 0));
          const newDiff = Math.abs(result.inventory.bunkers - (targetBunkers ?? 0)) + Math.abs(result.inventory.fuel - (targetFuel ?? 0));
          if (newDiff < currDiff) {
            bestEffort = { defText, bunkers: result.inventory.bunkers, fuel: result.inventory.fuel };
          }
        }
        console.log(`[GEN_RETRY] Attempt ${i + 1} failed: inventory count mismatch (bunkers=${result.inventory.bunkers}, fuel=${result.inventory.fuel})`);
        // After bestEffortThreshold attempts, accept the closest match
        if (i + 1 >= bestEffortThreshold && bestEffort) {
          console.log(`[GEN_OK] Best-effort match after ${i + 1} attempts (bunkers=${bestEffort.bunkers}, fuel=${bestEffort.fuel})`);
          return bestEffort.defText;
        }
      }
      console.log(`[GEN_RETRY] Attempt ${i + 1} failed: ${result.errors.length} errors`);
      for (const e of result.errors) console.log(`  ERROR: ${e}`);
    }
    throw new Error(`Failed to generate valid level after ${maxAttempts} attempts. last error message: ${result.errors[result.errors.length - 1]}`);
  }

